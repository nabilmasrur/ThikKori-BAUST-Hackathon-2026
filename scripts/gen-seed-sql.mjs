// Renders supabase/seed.sql from the same seed module the local backend uses,
// so the two backends can never drift apart.
//
//   npm run seed:sql
//
// Output is deterministic apart from the reference date, which is "now" at
// generation time. The TypeScript module is bundled through esbuild (already
// present as a Vite dependency) rather than imported directly, so the source
// keeps its normal import style.

import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../supabase/seed.sql');
const tmp = resolve(here, '../node_modules/.thikkori-seed.mjs');

await build({
  entryPoints: [resolve(here, '../src/data/seed.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  outfile: tmp,
  logLevel: 'silent',
});

const { buildSeed } = await import(pathToFileURL(tmp).href);
const db = buildSeed(new Date());

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) {
    if (v.length && typeof v[0] === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
    return `ARRAY[${v.map((x) => q(x)).join(', ')}]::text[]`;
  }
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table, rows, columns) {
  if (!rows.length) return `-- ${table}: no rows\n`;
  const cols = columns ?? Object.keys(rows[0]);
  const chunks = [];
  for (let i = 0; i < rows.length; i += 200) chunks.push(rows.slice(i, i + 200));
  return chunks
    .map(
      (chunk) =>
        `insert into ${table} (${cols.join(', ')}) values\n` +
        chunk.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n') +
        '\non conflict do nothing;\n',
    )
    .join('\n');
}

const order = [
  ['provider_tiers', db.provider_tiers],
  ['service_categories', db.service_categories],
  ['customers', db.customers],
  ['providers', db.providers],
  ['requests', db.requests],
  ['bookings', db.bookings],
  ['request_matches', db.request_matches],
  ['status_history', db.status_history],
  ['invoices', db.invoices],
  ['reviews', db.reviews],
  ['loyalty', db.loyalty],
  ['challenges', db.challenges],
  ['provider_costs', db.provider_costs],
  ['admin_announcements', db.admin_announcements],
  ['reported_issues', db.reported_issues],
];

const header = `-- ═══════════════════════════════════════════════════════════════════
-- ThikKori — seed data   (generated by scripts/gen-seed-sql.mjs)
-- Generated: ${new Date().toISOString()}
--
-- Covers every table, six months of paid history for the finance and
-- analytics charts, and one live booking sitting at "in progress" with a
-- pending invoice behind a scannable QR token.
--
-- Run after 0001_schema.sql, 0002_rls.sql and 0003_realtime.sql.
-- ═══════════════════════════════════════════════════════════════════

begin;

`;

const body = order.map(([table, rows]) => `-- ── ${table} (${rows.length}) ${'─'.repeat(Math.max(0, 46 - table.length))}\n${insert(table, rows)}`).join('\n');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${header}${body}\ncommit;\n`, 'utf8');

rmSync(tmp, { force: true });

const total = order.reduce((s, [, rows]) => s + rows.length, 0);
console.log(`seed.sql written — ${total} rows across ${order.length} tables`);
